ServerEvents.tags("item", (event) => {
  global.resources_ores_ingot.forEach((mod) => {
    mod.materials.forEach((material) => {
      const modID = mod.modPrefixOverride ? mod.modPrefixOverride : "ftbmaterials";

      event.add(`${global.tag_prefix}:raw_blocks/${material}`, [
        `${modID}:raw_${material}_block`,
        `${modID}:${material}_raw_block`,
      ]);

      if (material !== "steel") {
        event.add(`${global.tag_prefix}:shards/${material}`, `geore:${material}_shard`);
      }
    });
  });

  event.add("c:hidden_from_recipe_viewers", global.fluids);
  event.removeAllTagsFrom(unfiItemsToRemove);
  event.add("c:hidden_from_recipe_viewers", unfiItemsToRemove);

  global.usedOres.forEach((ore) => {
    event.add("ftb:ores/stone", `ftbmaterials:${ore.material}_stone_ore`);
  });

  event.add("rftoolsbase:shards", "ftbmaterials:dimensional_shard");
  event.add("forge:gems/dimensional_shard", "rftoolsbase:dimensionalshard");
  event.add("forge:ores/dimensional_shard", [
    "rftoolsbase:dimensionalshard_overworld",
    "rftoolsbase:dimensionalshard_nether",
    "rftoolsbase:dimensionalshard_end",
  ]);

  event.add("forge:raw_nuggets/steel", "tconstruct:steel_shard");
});

ServerEvents.tags("block", (event) => {
  event.removeAllTagsFrom(unfiBlocksToRemove);
  event.add("forge:ores/dimensional_shard", [
    "rftoolsbase:dimensionalshard_overworld",
    "rftoolsbase:dimensionalshard_nether",
    "rftoolsbase:dimensionalshard_end",
  ]);
});
ServerEvents.tags("fluid", (event) => {
  const fluidIds = global.fluids.map((id) => (id.endsWith("_bucket") ? id.slice(0, -7) : id));

  event.removeAllTagsFrom(fluidIds);
  event.add("c:hidden_from_recipe_viewers", ["tconstruct:molten_refined_glowstone", "tconstruct:molten_refined_obsidian"])
  event.add("c:hidden_from_recipe_viewers", fluidIds);
});
